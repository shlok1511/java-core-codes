
class gbsize
{
    public static void main(String args[])
    {
        float gb, mb, kb;

        gb = 2;

        System.out.println("Size in GB = " + gb);

        mb = gb * 1024;
        System.out.println("Size in MB = " + mb);

        kb = mb * 1024;
        System.out.println("Size in KB = " + kb);
    }
}
